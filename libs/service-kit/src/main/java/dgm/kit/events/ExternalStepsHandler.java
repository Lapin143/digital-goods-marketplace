package dgm.kit.events;

/**
 * Обработчик события с внешними шагами: решение и вызовы соседей идут вне транзакции базы, изменение данных и отметка
 * {@code processed_event} в одной короткой транзакции после них (правило 9 руководства среза 2, c4-components-order-service.md, 3.1;
 * для HTTP то же сделано режимом {@code x-idempotency-external-steps}, Р-150).
 *
 * <p>Обычный {@link EventHandler#handle} выполняется внутри транзакции каркаса, поэтому вызвать в нём соседа нельзя: медленный ответ держал
 * бы соединение с базой. Здесь порядок другой:
 * <ol>
 *   <li>каркас проверяет, не обработано ли событие ({@link ProcessedEvents#isProcessed}); дубль пропускается, соседи не вызываются;</li>
 *   <li>{@link #prepare} читает состояние, решает и вызывает соседей без транзакции; результат это действие для шага 3;</li>
 *   <li>каркас открывает транзакцию, записывает {@code processed_event} и выполняет действие. Отметка, изменение данных и записи в Outbox
 *       фиксируются вместе: исключение откатывает всё, событие придёт снова.</li>
 * </ol>
 * Повтор события (после сбоя между шагами 2 и 3, после отката или временной ошибки) выполнит {@link #prepare} заново, поэтому вызовы соседей в нём
 * должны быть идемпотентны (ключ идемпотентности выводится из шага и заказа, Р-149), а действие шага 3 обязано заново проверить состояние под
 * блокировкой: между шагами 2 и 3 данные могли измениться (сторож, другое событие того же заказа).
 */
public interface ExternalStepsHandler extends EventHandler {

    /** Действие шага 3: выполняется каркасом внутри транзакции, где уже записан {@code processed_event}. */
    @FunctionalInterface
    interface TransactionalStep {

        /** Применяет изменение; пишет в Outbox той же транзакцией. Исключение откатывает транзакцию, включая отметку обработанного. */
        HandleResult apply() throws Exception;
    }

    /**
     * Шаг 2: решение и вызовы соседей вне транзакции.
     *
     * @return действие для транзакции; {@code null} равно действию «ничего не менять» (событие всё равно отмечается обработанным)
     * @throws FatalEventException     неисправимая ошибка: DLQ сразу
     * @throws RetryableEventException временная ошибка (сосед недоступен): повторы 1, 5, 25 секунд, затем DLQ
     */
    TransactionalStep prepare(EventEnvelope event) throws Exception;

    /** Обычный путь для этих обработчиков закрыт: каркас вызывает {@link #prepare}. */
    @Override
    default HandleResult handle(EventEnvelope event) {
        throw new IllegalStateException("Обработчик " + name() + " работает с внешними шагами: каркас вызывает prepare, а не handle");
    }
}
