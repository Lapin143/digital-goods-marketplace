#!/usr/bin/env bash
# Проверка проверки: дымовой тест обязан стать красным, если в «хорошем» пути испорчен токен, область или сертификат вызывающего сервиса.
# Тест, который ни разу не краснел, ничего не гарантирует (шаг 17 Ф3). Стенд поднят как для make smoke (набор с шлюзом и сервисами, DEBUG=1,
# make keycloak-users). Каждый запуск идёт в режиме SMOKE_SABOTAGE и проверяет только начало пути: вход, операции через шлюз, внутренний вызов mTLS.
#
#   token   последние знаки подписи токена покупателя заменены                  → GET /api/v1/orders даёт 401, а тест ждёт 200
#   scope   вместо токена покупателя токен продавца (нет области orders.read)   → 403 вместо 200
#   cert    внутренний вызов catalog-service с сертификатом чужого сервиса      → 403 вместо «фильтр вызывающего пропустил»
set -uo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
cd "$HERE/../.."
source tools/stand-checks/lib.sh

for mode in token scope cert; do
  OUT=$(SMOKE_SABOTAGE=$mode python3 tools/stand-checks/smoke.py 2>&1); RC=$?
  if [ $RC -ne 0 ] && grep -q 'ОШИБКА' <<<"$OUT"; then
    ok "порча «$mode»: дымовой тест красный (код $RC, не прошло проверок: $(grep -c '^  - ' <<<"$OUT"))"
  else
    bad "порча «$mode»: дымовой тест остался зелёным (код $RC), он ничего не ловит" "$OUT"
  fi
done
# Что без порчи тот же тест зелёный, показывает предыдущий шаг CI (make smoke): красный цвет вызван порчей, а не поломкой проверки.
finish
