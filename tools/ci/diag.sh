#!/usr/bin/env bash
# Запуск команды с диагностикой для CI.
#
#   tools/ci/diag.sh "Название шага" команда аргументы...
#
# Что делает: выполняет команду и печатает её вывод как обычно. Если команда упала, дополнительно
# печатает аннотацию «::error title=…::…» со строками, которые объясняют ошибку. Аннотации задания видны
# в интерфейсе GitHub и читаются по REST API без входа в аккаунт, а журналы запусков без входа недоступны.
# Так причина падения видна сразу, без повторного запуска.
#
# Настройки (переменные окружения):
#   DIAG_FILTER  регулярное выражение (grep -E): сначала в аннотацию попадают подходящие строки журнала
#   DIAG_MAX     сколько подходящих строк брать, по умолчанию 25
#   DIAG_TAIL    сколько последних строк журнала добавить, по умолчанию 25
#   DIAG_LOG     куда сохранить полный журнал, по умолчанию временный файл
#
# Код выхода равен коду выхода команды.
set -uo pipefail

if [ "$#" -lt 2 ]; then
  echo "Использование: $0 \"Название шага\" команда [аргументы...]" >&2
  exit 64
fi

title="$1"; shift
log="${DIAG_LOG:-$(mktemp)}"
max="${DIAG_MAX:-25}"
tail_n="${DIAG_TAIL:-25}"

"$@" 2>&1 | tee "$log"
rc=${PIPESTATUS[0]}

# Экранирование по правилам команд рабочего процесса GitHub: % \r \n в сообщении, ещё , и : в заголовке.
esc_msg()   { sed -e 's/%/%25/g' -e 's/\r/%0D/g' | sed -e ':a;N;$!ba;s/\n/%0A/g'; }
esc_title() { sed -e 's/%/%25/g' -e 's/,/%2C/g' -e 's/:/%3A/g'; }

if [ "$rc" -ne 0 ]; then
  {
    if [ -n "${DIAG_FILTER:-}" ]; then
      grep -E -- "$DIAG_FILTER" "$log" | head -n "$max"
      echo "-----"
    fi
    tail -n "$tail_n" "$log"
  } | cut -c1-300 | esc_msg > "$log.msg"
  t=$(printf '%s (код %s)' "$title" "$rc" | esc_title)
  # Сообщение аннотации ограничено по размеру, берём не больше 6000 символов.
  printf '::error title=%s::%s\n' "$t" "$(head -c 6000 "$log.msg")"
fi
exit "$rc"
