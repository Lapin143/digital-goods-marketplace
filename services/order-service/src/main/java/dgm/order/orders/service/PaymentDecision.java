package dgm.order.orders.service;

/**
 * Решение оркестратора по подтверждённому платежу (шаг 5 саги, ADR-004, ADR-013), принятое вне транзакции. Применяется потом одной короткой
 * транзакцией, которая заново проверяет статус заказа под блокировкой строки.
 */
public sealed interface PaymentDecision {

    /** Заказ не требует действий: платёж уже учтён (повтор, E5) или это аномалия, которую разбирает администратор. */
    record Ignore(String reason) implements PaymentDecision {
    }

    /** Резерв закреплён: заказ «оплачен» (T4 для «ожидает оплаты», T7 для «отменён», поздняя оплата). */
    record Pay() implements PaymentDecision {
    }

    /** Ключей на весь заказ нет (INV-05): заказ остаётся «отменён» (при «ожидает оплаты» сначала T6), деньги возвращаются. */
    record Refund() implements PaymentDecision {
    }

    /**
     * Сейчас решить нельзя, событие нужно обработать позже: подтверждение обогнало переход «ожидает оплаты» (заказ ещё «создан») или сервис
     * остатков не ответил. Платёж остаётся подтверждённым, обработка повторяется с паузами 1, 5, 25 секунд, затем DLQ (ADR-011).
     */
    record Wait(String reason) implements PaymentDecision {
    }
}
