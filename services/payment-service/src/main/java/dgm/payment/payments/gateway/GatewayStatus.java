package dgm.payment.payments.gateway;

/**
 * Состояние платежа у шлюза в модели платформы (ACL, ADR-015): статусы шлюза сводятся к шести значениям, незнакомый статус это
 * {@link #UNKNOWN}, а не ошибка разбора.
 */
public enum GatewayStatus {
    /** Ждёт оплаты. */
    PENDING,
    /** Оплачен. */
    PAID,
    /** Отклонён. */
    DECLINED,
    /** Срок сессии у шлюза вышел, оплаты не было. */
    EXPIRED,
    /** Возврат принят и выполняется. */
    REFUNDING,
    /** Деньги возвращены. */
    REFUNDED,
    /** Статус, которого платформа не знает. */
    UNKNOWN
}
