package dgm.platform.notification.api;

import java.util.Map;

/**
 * Прямая отправка письма для других модулей платформы (подпакет {@code api}, правило модульности 1): письмо уходит провайдеру сразу, минуя
 * очередь уведомлений. Так отправляется письмо с одноразовым кодом на новый адрес при смене e-mail (SEQ-04, шаг 13): код нельзя положить
 * в базу, а очередь хранит параметры письма до отправки (правило 17, INV-44). Повторов нет: если провайдер не принял письмо, вызывающий
 * получает ошибку и покупатель запрашивает код ещё раз. Адрес и параметры живут только в памяти на время вызова.
 */
public interface DirectMail {

    /** Шаблон письма с кодом смены e-mail; параметр {@code code}. */
    String EMAIL_CHANGE_CODE = "email-change-code";

    /**
     * @param to       адрес получателя
     * @param template шаблон, который разрешено отправлять напрямую
     * @param params   параметры шаблона
     * @throws InvalidNotificationException шаблона нет, он не для прямой отправки или параметры ему не подходят
     * @throws DirectMailException          провайдер не принял письмо или не ответил вовремя
     */
    void send(String to, String template, Map<String, Object> params);
}
