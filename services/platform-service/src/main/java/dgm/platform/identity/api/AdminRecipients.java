package dgm.platform.identity.api;

import java.util.List;
import java.util.UUID;

/**
 * Получатели оповещений администратору для других модулей платформы (подпакет {@code api}, правило модульности 1). Письма администратору
 * (возврат ушёл в ручную очередь, выдача закончилась ошибкой, 30 минут без доставки) уходят всем активным администраторам: ни у одного
 * из них нет «главного» адреса, а потеря единственного письма хуже лишней копии (Р-153).
 */
public interface AdminRecipients {

    /** Предел числа получателей: администраторов единицы, а пачка писем на событие должна оставаться короткой. */
    int MAX = 20;

    /**
     * @return идентификаторы активных администраторов, новые выше, не больше {@link #MAX}; адрес и имя письму даёт {@link UserContacts} в
     *         момент отправки, анонимизированные записи не входят
     */
    List<UUID> activeAdminIds();
}
