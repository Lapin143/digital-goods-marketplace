package dgm.platform.identity.api;

import java.util.Optional;
import java.util.UUID;

/**
 * Владелец профиля продавца для других модулей платформы (подпакет {@code api}, правило модульности 1). События каталога называют продавца
 * идентификатором профиля ({@code sellerId}), а письмо адресуется учётной записи: идентификатор профиля и идентификатор пользователя
 * различны (INV-36, Р-18), и связь между ними хранит только {@code identity}. Адрес и имя письму даёт {@link UserContacts} в момент отправки.
 */
public interface SellerRecipients {

    /**
     * @return идентификатор учётной записи, к которой привязан профиль продавца; пусто, если профиль ни к какой записи не привязан (роль
     *         снята или запись не знает такого профиля), анонимизированные записи не входят
     */
    Optional<UUID> ownerOf(UUID sellerId);
}
