package dgm.platform.identity.api;

import java.util.Optional;
import java.util.UUID;

/**
 * Контактные данные получателя для других модулей платформы (подпакет {@code api}, правило модульности 1). Уведомления спрашивают адрес
 * в момент отправки и нигде его не сохраняют, поэтому смена адреса и анонимизация действуют на все письма, ещё стоящие в очереди (INV-44).
 */
public interface UserContacts {

    /**
     * @return контакт активной записи; пусто, если записи нет, она деактивирована или анонимизирована: такому получателю не пишут
     */
    Optional<Contact> findActive(UUID userId);

    /**
     * Прежний адрес после смены e-mail: письмо о смене уходит и на него (UC-04, 6a.6). Адрес хранится 7 суток, потом очищается.
     *
     * @return контакт с прежним адресом; пусто, если смены не было, срок хранения истёк, запись деактивирована или анонимизирована
     */
    Optional<Contact> findPrevious(UUID userId);
}
