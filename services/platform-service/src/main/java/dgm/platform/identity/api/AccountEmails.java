package dgm.platform.identity.api;

/**
 * Занятость адресов e-mail для других модулей платформы (подпакет {@code api}, правило модульности 1). Поддержка проверяет, что новый
 * адрес не привязан к учётной записи (INV-34), до отправки кода и ещё раз после подтверждения телефона.
 */
public interface AccountEmails {

    /**
     * @param email адрес в нормализованном виде
     * @return адрес уже стоит в какой-либо учётной записи: в чужой (в том числе деактивированной, пока запись не анонимизирована) или в
     *         той же, чей адрес меняют; использовать его нельзя. Прежние адреса, которые хранятся 7 суток ради письма о смене, не считаются
     */
    boolean isUnavailable(String email);
}
