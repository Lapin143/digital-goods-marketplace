package dgm.platform.support.service;

import java.util.function.Supplier;

/**
 * Транзакция модуля {@code support} для операций по запросу пользователя (ADR-005): строка обращения и событие в Outbox фиксируются
 * вместе или откатываются вместе. Внутри транзакции охранника идемпотентности того же модуля действие присоединяется к ней, а не
 * открывает вторую. Отдельный интерфейс нужен, чтобы службу проверяли модульными тестами без базы.
 */
public interface SupportTransaction {

    /** Выполняет действие в транзакции; исключение откатывает её и летит наружу без изменений. */
    <T> T execute(Supplier<T> action);
}
